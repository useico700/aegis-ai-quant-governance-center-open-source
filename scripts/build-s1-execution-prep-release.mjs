const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const staging = await fs.mkdtemp(path.join(os.tmpdir(), 's1-execution-release-'));
try {
  const manifestFiles = [];
  for (const relative of files) {
    const source = path.join(root, relative);
    const stat = await fs.lstat(source);
    if (!stat.isFile() || stat.isSymbolicLink() || /(^|\/)(\.env|runtime|secrets)(\/|$)/.test(relative)) throw new Error('UNSAFE_RELEASE_INPUT');
    const data = await fs.readFile(source);
    const target = path.join(staging, relative);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, data, { mode: 0o644 });
    manifestFiles.push({ path: relative, bytes: data.length, sha256: hash(data) });
  }
  const sourceFingerprint = hash(JSON.stringify(manifestFiles));
  const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z');
  const releaseId = `aegis-s1-execution-${stamp}-${sourceFingerprint.slice(0, 12)}`;
  await fs.writeFile(path.join(staging, 'release-manifest.json'), JSON.stringify({
    schemaVersion: 2,
    releaseId,
    sourceFingerprint,
    mode: 'LIVE_CAPABLE_REQUIRES_SERVER_AUTHORIZATION',
    realOrdersAllowed: true,
    activationControl: '/etc/aegis/s1-execution-control/authorization.json',
    secretsIncluded: false,
    historicalRuntimeIncluded: false,
    files: manifestFiles,
  }, null, 2));
  const output = path.join(root, 'dist-production'); await fs.mkdir(output, { recursive: true });
  const archive = path.join(output, `${releaseId}.tar.gz`);
  execFileSync('/usr/bin/tar', ['--no-xattrs', '-czf', archive, '-C', staging, '.'], { env: { ...process.env, COPYFILE_DISABLE: '1' } });
  const data = await fs.readFile(archive), archiveSha256 = hash(data);
  await fs.writeFile(`${archive}.sha256`, `${archiveSha256}  ${path.basename(archive)}\n`);
  process.stdout.write(JSON.stringify({ releaseId, archive, archiveSha256, sourceFingerprint, fileCount: files.length, archiveBytes: data.length }) + '\n');
} finally { await fs.rm(staging, { recursive: true, force: true }); }
